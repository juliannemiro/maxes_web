CREATE TABLE IF NOT EXISTS analytics_carrito (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_analytics_session VARCHAR(100) NOT NULL UNIQUE,
    estado VARCHAR(30) NOT NULL DEFAULT 'activo',
    etapa VARCHAR(30) NOT NULL DEFAULT 'carrito',
    fue_abandonado BOOLEAN NOT NULL DEFAULT FALSE,
    cantidad_reactivaciones INTEGER NOT NULL DEFAULT 0,
    tipo_precio VARCHAR(20),
    tipo_dispositivo VARCHAR(30) NOT NULL DEFAULT 'desconocido',
    sistema_operativo VARCHAR(50) NOT NULL DEFAULT 'otro',
    navegador VARCHAR(50) NOT NULL DEFAULT 'otro',
    cantidad_productos INTEGER NOT NULL DEFAULT 0,
    cantidad_unidades INTEGER NOT NULL DEFAULT 0,
    cantidad_favoritos INTEGER NOT NULL DEFAULT 0,
    monto_estimado NUMERIC(18, 2) NOT NULL DEFAULT 0,
    fecha_hora_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_hora_inicio_catalogo TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_hora_ultima_actividad TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_hora_inicio_pedido TIMESTAMPTZ,
    fecha_hora_marcado_abandonado TIMESTAMPTZ,
    fecha_hora_ultima_reactivacion TIMESTAMPTZ,
    fecha_hora_pedido_generado TIMESTAMPTZ,
    segundos_navegacion_activa INTEGER NOT NULL DEFAULT 0,
    pedido_id INTEGER UNIQUE REFERENCES pedido_web(id) ON DELETE SET NULL,
    origen_campania VARCHAR(100),
    medio_campania VARCHAR(100),
    nombre_campania VARCHAR(150),
    pagina_ingreso VARCHAR(500),
    sitio_origen VARCHAR(500),
    CONSTRAINT analytics_carrito_estado_check
        CHECK (estado IN ('activo', 'abandonado', 'pedido_generado')),
    CONSTRAINT analytics_carrito_etapa_check
        CHECK (etapa IN ('carrito', 'formulario_pedido', 'pedido_generado'))
);

