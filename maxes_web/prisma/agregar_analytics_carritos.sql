DROP FUNCTION IF EXISTS marcar_carritos_abandonados_analytics();

CREATE OR REPLACE FUNCTION analytics_marcar_carritos_abandonados()
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    cantidad_marcada INTEGER;
BEGIN
    UPDATE analytics_carrito
    SET
        estado = 'abandonado',
        fue_abandonado = TRUE,
        fecha_hora_marcado_abandonado =
            COALESCE(fecha_hora_marcado_abandonado, CURRENT_TIMESTAMP)
    WHERE estado = 'activo'
      AND cantidad_productos > 0
      AND pedido_id IS NULL
      AND fecha_hora_ultima_actividad <= CURRENT_TIMESTAMP - INTERVAL '12 hours';

    GET DIAGNOSTICS cantidad_marcada = ROW_COUNT;
    RETURN cantidad_marcada;
END;
$$;
