-- Recuperación histórica segura: si la sesión nunca salió del catálogo, todo
-- su tiempo activo registrado pertenece a esa sección. Las sesiones que sí
-- llegaron al formulario no se reparten porque no puede reconstruirse el corte.
UPDATE analytics_sesion
SET segundos_activos_catalogo = segundos_navegacion_activa
WHERE segundos_activos_catalogo IS NULL
  AND etapa = 'catalogo';
CREATE UNIQUE INDEX IF NOT EXISTS analytics_favorito_evento_id_evento_idx
    ON analytics_favorito_evento(id_evento);
CREATE UNIQUE INDEX IF NOT EXISTS analytics_compartido_id_evento_idx
    ON analytics_articulo_compartido(id_evento);

CREATE INDEX IF NOT EXISTS analytics_sesion_fecha_inicio_idx
    ON analytics_sesion (fecha_hora_inicio);
CREATE INDEX IF NOT EXISTS analytics_sesion_visitante_fecha_idx
    ON analytics_sesion (id_analytics_visitor, fecha_hora_inicio);
CREATE INDEX IF NOT EXISTS analytics_sesion_carrito_idx
    ON analytics_sesion (carrito_analytics_id);

-- Conserva la serie histórica: cada registro anterior representaba a la vez
-- una sesión y un carrito. Los nuevos registros separan ambos conceptos.
INSERT INTO analytics_sesion (
    id_analytics_session, id_analytics_visitor, carrito_analytics_id,
    fecha_hora_inicio, fecha_hora_ultima_actividad, segundos_navegacion_activa,
    etapa, pedido_generado, tipo_dispositivo, sistema_operativo, navegador,
    origen_campania, medio_campania, nombre_campania, pagina_ingreso, sitio_origen
)
SELECT
    carrito.id_analytics_session,
    'legacy_' || carrito.id::text,
    carrito.id,
    carrito.fecha_hora_inicio_catalogo,
    carrito.fecha_hora_ultima_actividad,
    carrito.segundos_navegacion_activa,
    CASE
        WHEN carrito.etapa = 'pedido_generado' THEN 'pedido_generado'
        WHEN carrito.etapa = 'formulario_pedido' THEN 'formulario_pedido'
        ELSE 'catalogo'
    END,
    carrito.estado = 'pedido_generado',
    carrito.tipo_dispositivo,
    carrito.sistema_operativo,
    carrito.navegador,
    carrito.origen_campania,
    carrito.medio_campania,
    carrito.nombre_campania,
    carrito.pagina_ingreso,
    carrito.sitio_origen
FROM analytics_carrito AS carrito
ON CONFLICT (id_analytics_session) DO NOTHING;

COMMENT ON TABLE analytics_sesion IS
    'Visitas anonimas de 30 minutos de inactividad; varias sesiones pueden retomar un mismo carrito.';
