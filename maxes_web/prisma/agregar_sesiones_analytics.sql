CREATE TABLE IF NOT EXISTS analytics_sesion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_analytics_session VARCHAR(100) NOT NULL UNIQUE,
    id_analytics_visitor VARCHAR(100) NOT NULL,
    carrito_analytics_id INTEGER NOT NULL
        REFERENCES analytics_carrito(id) ON DELETE CASCADE,
    fecha_hora_inicio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_hora_ultima_actividad TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    segundos_navegacion_activa INTEGER NOT NULL DEFAULT 0,
    etapa VARCHAR(30) NOT NULL DEFAULT 'catalogo',
    pedido_generado BOOLEAN NOT NULL DEFAULT FALSE,
    tipo_dispositivo VARCHAR(30) NOT NULL DEFAULT 'desconocido',
    sistema_operativo VARCHAR(50) NOT NULL DEFAULT 'otro',
    navegador VARCHAR(50) NOT NULL DEFAULT 'otro',
    origen_campania VARCHAR(100),
    medio_campania VARCHAR(100),
    nombre_campania VARCHAR(150),
    contenido_campania VARCHAR(150),
    termino_campania VARCHAR(150),
    id_click_google VARCHAR(200),
    id_click_meta VARCHAR(200),
    pagina_ingreso VARCHAR(500),
    sitio_origen VARCHAR(500),
    CONSTRAINT analytics_sesion_etapa_check
        CHECK (etapa IN ('catalogo', 'formulario_pedido', 'pedido_generado'))
);

